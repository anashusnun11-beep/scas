import { ArrowLeftIcon, FileMagnifyingGlassIcon } from "@phosphor-icons/react/ssr";
import type { Metadata } from "next";
import Link from "next/link";
import { notFound } from "next/navigation";
import { ReportChart } from "@/components/admin/report-chart";
import { ReportSummary } from "@/components/admin/report-summary";
import { ReportTable } from "@/components/admin/report-table";
import { KpmLogo } from "@/components/brand/kpm-logo";
import { PrintButton } from "@/components/student/print-button";
import { buttonClasses } from "@/components/ui/button";
import { EmptyState } from "@/components/ui/empty-state";
import { requireRole } from "@/lib/auth/guard";
import { formatTimestamp } from "@/lib/dates";
import { formatRange, reportCode, reportTypeLabel } from "@/lib/reports";
import { getReport } from "@/server/queries/reports";

export const metadata: Metadata = { title: "Report | SCAS" };

/**
 * FR16 report view (SD13 steps 8-9) and FR17 Print Report (SD13 opt): a print view with print CSS,
 * like the slip. Always light, so it looks the same on screen and on paper whatever the theme.
 */
export default async function ReportPage({ params }: { params: Promise<{ id: string }> }) {
  await requireRole("ADMIN");
  const { id } = await params;
  const report = await getReport(Number(id));
  if (!report) notFound();

  const { data } = report;
  const title = reportTypeLabel[report.reportType];
  const period = formatRange(report.dateFrom, report.dateTo);

  return (
    <div className="grid gap-4">
      <div className="flex flex-wrap items-center justify-between gap-3 print:hidden">
        <Link href="/admin/reports" className={buttonClasses({ variant: "secondary" })}>
          <ArrowLeftIcon aria-hidden className="size-4" />
          All reports
        </Link>
        {data.total > 0 && <PrintButton label="Print report" />}
      </div>

      <article
        data-theme="light"
        className="grid min-w-0 gap-6 rounded-card border border-line bg-surface p-5 text-ink shadow-card sm:p-8 print:gap-5 print:border-0 print:p-0 print:shadow-none"
      >
        <header className="grid gap-4 border-b-2 border-ink pb-5">
          <div className="flex flex-wrap items-start justify-between gap-4">
            <div className="flex min-w-0 items-center gap-4">
              <KpmLogo className="h-14 p-0" priority />
              <div className="min-w-0">
                <h2 className="font-display text-2xl font-bold leading-tight sm:text-title">{title}</h2>
                <p className="text-sm text-muted">Student Consultation Appointment System, KPM Beranang</p>
              </div>
            </div>
            <p className="font-mono text-lg font-bold">{reportCode(report.id)}</p>
          </div>
          <dl className="grid gap-x-8 gap-y-2 text-sm sm:grid-cols-3">
            <div>
              <dt className="text-muted">Period</dt>
              <dd className="font-semibold">{period}</dd>
            </div>
            <div>
              <dt className="text-muted">Generated</dt>
              <dd className="font-semibold">{formatTimestamp(report.generatedAt)}</dd>
            </div>
            <div>
              <dt className="text-muted">Generated by</dt>
              <dd className="font-semibold">
                {report.admin.user.name} <span className="font-mono font-normal text-muted">({report.admin.adminId})</span>
              </dd>
            </div>
          </dl>
        </header>

        {data.total === 0 ? (
          <EmptyState icon={FileMagnifyingGlassIcon} title="No record for the selected period">
            There are no appointments from {period} any more. Generate a new report for another period.
          </EmptyState>
        ) : (
          <>
            <ReportSummary data={data} />
            <section className="grid gap-4 break-inside-avoid" aria-labelledby="report-chart">
              <h3 id="report-chart" className="font-display text-subheading font-semibold">
                {report.reportType === "BY_LECTURER" ? "Appointments by lecturer" : "Appointments by status"}
              </h3>
              <ReportChart type={report.reportType} data={data} />
            </section>
            <section className="grid gap-3 break-inside-avoid" aria-labelledby="report-table">
              <h3 id="report-table" className="font-display text-subheading font-semibold">
                Summary table
              </h3>
              <ReportTable type={report.reportType} data={data} />
            </section>
          </>
        )}

        <footer className="flex flex-wrap justify-between gap-2 border-t border-line pt-4 text-xs text-muted">
          <p>Counted by consultation date, both dates included. Figures are recalculated from current data each time the report is opened.</p>
          <p className="hidden print:block">Printed {formatTimestamp(new Date())}</p>
        </footer>
      </article>
    </div>
  );
}
